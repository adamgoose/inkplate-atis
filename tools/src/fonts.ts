/**
 * Converts the Spleen BDF fonts into the C tables the firmware draws text with
 * (firmware/inkplate_atis/src/fonts.cpp). Only printable ASCII is kept.
 *
 *   bun run fonts
 */
import { BunRuntime, BunServices } from "@effect/platform-bun"
import { Console, Effect, FileSystem } from "effect"
import { fileURLToPath } from "node:url"

const FIRST = 0x20
const LAST = 0x7e

const FONTS = [
  { name: "TINY", file: "spleen-6x12.bdf" },
  { name: "SMALL", file: "spleen-8x16.bdf" },
  { name: "MEDIUM", file: "spleen-12x24.bdf" },
  { name: "LARGE", file: "spleen-16x32.bdf" },
  { name: "HUGE", file: "spleen-32x64.bdf" }
] as const

interface Glyph {
  readonly box: readonly [width: number, height: number, xOffset: number, yOffset: number]
  /** One entry per row, MSB-first, `rowBits` wide. */
  readonly rows: ReadonlyArray<bigint>
  readonly rowBits: number
}

interface Bdf {
  readonly cellWidth: number
  readonly cellHeight: number
  readonly ascent: number
  readonly glyphs: ReadonlyMap<number, Glyph>
}

/** Parses the subset of BDF that fixed-cell bitmap fonts such as Spleen use. */
const parseBdf = (source: string): Bdf => {
  const glyphs = new Map<number, Glyph>()
  let cellWidth = 0
  let cellHeight = 0
  let ascent = 0
  let encoding = -1
  let box: Glyph["box"] = [0, 0, 0, 0]
  let rows: Array<bigint> | undefined
  let rowBits = 0

  for (const line of source.split("\n")) {
    if (rows !== undefined) {
      if (line.startsWith("ENDCHAR")) {
        glyphs.set(encoding, { box, rows, rowBits })
        rows = undefined
      } else {
        const hex = line.trim()
        rowBits = hex.length * 4
        rows.push(BigInt(`0x${hex}`))
      }
      continue
    }
    const [keyword, ...args] = line.trim().split(/\s+/)
    const nums = args.map(Number)
    switch (keyword) {
      case "FONTBOUNDINGBOX":
        cellWidth = nums[0] ?? 0
        cellHeight = nums[1] ?? 0
        break
      case "FONT_ASCENT":
        ascent = nums[0] ?? 0
        break
      case "ENCODING":
        encoding = nums[0] ?? -1
        break
      case "BBX":
        box = [nums[0] ?? 0, nums[1] ?? 0, nums[2] ?? 0, nums[3] ?? 0]
        break
      case "BITMAP":
        rows = []
        break
    }
  }
  return { cellWidth, cellHeight, ascent, glyphs }
}

/** Places a glyph in its full cell: `cellHeight` rows of `bytesPerRow` bytes, MSB-first. */
const cellBytes = (font: Bdf, glyph: Glyph | undefined): Array<number> => {
  const bytesPerRow = Math.ceil(font.cellWidth / 8)
  const out = new Array<number>(bytesPerRow * font.cellHeight).fill(0)
  if (glyph === undefined) return out
  const [width, height, xOffset, yOffset] = glyph.box
  const top = font.ascent - yOffset - height
  for (let row = 0; row < height; row++) {
    for (let col = 0; col < width; col++) {
      if (((glyph.rows[row] ?? 0n) >> BigInt(glyph.rowBits - 1 - col) & 1n) === 0n) continue
      const x = xOffset + col
      const y = top + row
      if (x < 0 || y < 0 || x >= font.cellWidth || y >= font.cellHeight) continue
      out[y * bytesPerRow + (x >> 3)]! |= 0x80 >> (x & 7)
    }
  }
  return out
}

const hex = (byte: number): string => `0x${byte.toString(16).padStart(2, "0")}`

const program = Effect.gen(function*() {
  const fs = yield* FileSystem.FileSystem
  const fontDir = fileURLToPath(new URL("../fonts/", import.meta.url))
  const out = fileURLToPath(new URL("../../firmware/inkplate_atis/src/fonts.cpp", import.meta.url))

  const parts = [
    "// Generated by tools/src/fonts.ts from the Spleen BDF fonts. Do not edit.",
    "// Spleen is Copyright (c) 2018-2026 Frederic Cambus, BSD 2-Clause; see tools/fonts/LICENSE-spleen.",
    `#include "fonts.h"`,
    ""
  ]
  for (const { file, name } of FONTS) {
    const font = parseBdf(yield* fs.readFileString(`${fontDir}${file}`))
    const lines: Array<string> = []
    for (let code = FIRST; code <= LAST; code++) {
      const glyph = font.glyphs.get(code) ?? font.glyphs.get(0x3f)
      lines.push(`    ${cellBytes(font, glyph).map(hex).join(",")},`)
    }
    parts.push(
      `static const uint8_t ${name}_BITMAP[] = {`,
      ...lines,
      "};",
      `const Font FONT_${name} = {${font.cellWidth}, ${font.cellHeight}, ${Math.ceil(font.cellWidth / 8)}, ${name}_BITMAP};`,
      ""
    )
  }
  yield* fs.writeFileString(out, parts.join("\n"))
  yield* Console.log(`${FONTS.length} fonts -> ${out}`)
})

program.pipe(Effect.provide(BunServices.layer), BunRuntime.runMain)
