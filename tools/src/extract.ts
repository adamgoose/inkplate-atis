/**
 * Extracts one airport's runway geometry from a Navigraph-style AIRAC SQLite
 * database (the navdata.s3db that SimToolkitPro ships) and bakes it into the
 * firmware as firmware/inkplate_atis/src/airport_data.cpp. The raw rows are
 * also kept in data/{ICAO}.json for reference.
 *
 *   bun run extract [ICAO] [path/to/navdata.s3db]
 */
import { BunRuntime, BunServices } from "@effect/platform-bun"
import { Database } from "bun:sqlite"
import { Console, Effect, FileSystem, Schema } from "effect"
import { homedir } from "node:os"
import { fileURLToPath } from "node:url"

const RunwayEnd = Schema.Struct({
  /** ARINC ident, e.g. "RW30L". */
  ident: Schema.String,
  /** Landing threshold position. */
  latitude: Schema.Number,
  longitude: Schema.Number,
  trueBearing: Schema.Number,
  magneticBearing: Schema.Number,
  lengthFt: Schema.Number,
  widthFt: Schema.Number,
  displacedThresholdFt: Schema.Number
})

const AirportData = Schema.Struct({
  ident: Schema.String,
  name: Schema.String,
  latitude: Schema.Number,
  longitude: Schema.Number,
  elevationFt: Schema.Number,
  airac: Schema.String,
  runways: Schema.Array(RunwayEnd)
})
type AirportData = typeof AirportData.Type

class AirportDataError extends Schema.TaggedError<AirportDataError>()("AirportDataError", {
  message: Schema.String,
  cause: Schema.optional(Schema.Defect())
}) {}

interface Pavement {
  /** Runway idents as spoken on the ATIS ("4", "30L") with the pavement end behind each threshold, in feet east and north of the airport reference point. */
  readonly ends: readonly [PavementEnd, PavementEnd]
  readonly widthFt: number
}

interface PavementEnd {
  readonly name: string
  readonly x: number
  readonly y: number
}

const FEET_PER_DEGREE_LATITUDE = 364_567

const spokenName = (ident: string): string => ident.replace(/^RW/, "").replace(/^0/, "")

const reciprocal = (name: string): string => {
  const match = /^(\d{1,2})([LRC]?)$/.exec(name)
  if (!match) return name
  const number = ((Number(match[1]) + 17) % 36) + 1
  const side = match[2] === "L" ? "R" : match[2] === "R" ? "L" : match[2]
  return `${number}${side}`
}

/**
 * Projects the runway thresholds onto a flat plane around the airport and pairs
 * opposite ends into strips of pavement. Displaced thresholds are moved back to
 * the pavement end so the strip is drawn at its full length.
 */
const pavements = (airport: AirportData): Array<Pavement> => {
  const feetPerDegreeLongitude = FEET_PER_DEGREE_LATITUDE * Math.cos((airport.latitude * Math.PI) / 180)
  const ends = airport.runways.map((runway) => {
    const bearing = (runway.trueBearing * Math.PI) / 180
    const back = runway.displacedThresholdFt
    return {
      name: spokenName(runway.ident),
      widthFt: runway.widthFt,
      x: (runway.longitude - airport.longitude) * feetPerDegreeLongitude - Math.sin(bearing) * back,
      y: (runway.latitude - airport.latitude) * FEET_PER_DEGREE_LATITUDE - Math.cos(bearing) * back
    }
  })

  const out: Array<Pavement> = []
  const used = new Set<string>()
  for (const end of ends) {
    if (used.has(end.name)) continue
    const other = ends.find((candidate) => candidate.name === reciprocal(end.name))
    if (other === undefined) continue
    used.add(end.name).add(other.name)
    out.push({
      ends: [{ name: end.name, x: end.x, y: end.y }, { name: other.name, x: other.x, y: other.y }],
      widthFt: end.widthFt
    })
  }
  return out
}

const cString = (text: string): string => JSON.stringify(text.replace(/[^\x20-\x7e]/g, "?"))

const toCpp = (airport: AirportData): string => {
  const end = (e: PavementEnd) => `{${cString(e.name)}, ${e.x}, ${e.y}}`
  const strips = pavements(airport)
  return [
    `// Generated by tools/src/extract.ts from AIRAC ${airport.airac}. Do not edit.`,
    `#include "airport.h"`,
    "",
    "static const Pavement PAVEMENTS[] = {",
    ...strips.map((strip) => `    {{${end(strip.ends[0])}, ${end(strip.ends[1])}}, ${strip.widthFt}},`),
    "};",
    "",
    `const Airport AIRPORT = {${cString(airport.ident)}, ${cString(airport.name.replace(/[-/\s]+$/, ""))}, ${cString(airport.airac)}, PAVEMENTS, ${strips.length}};`,
    ""
  ].join("\n")
}

const AirportRow = Schema.Struct({
  airport_identifier: Schema.String,
  airport_name: Schema.String,
  airport_ref_latitude: Schema.Number,
  airport_ref_longitude: Schema.Number,
  elevation: Schema.Number
})

const RunwayRow = Schema.Struct({
  runway_identifier: Schema.String,
  runway_latitude: Schema.Number,
  runway_longitude: Schema.Number,
  runway_true_bearing: Schema.Number,
  runway_magnetic_bearing: Schema.Number,
  runway_length: Schema.Number,
  runway_width: Schema.Number,
  displaced_threshold_distance: Schema.Number
})

const HeaderRow = Schema.Struct({ current_airac: Schema.String })

const openReadonly = (path: string) =>
  Effect.acquireRelease(
    Effect.try({
      try: () => new Database(path, { readonly: true }),
      catch: (cause) => new AirportDataError({ message: `Cannot open navdata at ${path}`, cause })
    }),
    (db) => Effect.sync(() => db.close())
  )

const query = <S extends Schema.Top>(db: Database, schema: S, sql: string, ...params: Array<string>) =>
  Effect.try({
    try: () => db.query(sql).all(...params),
    catch: (cause) => new AirportDataError({ message: `Query failed: ${sql}`, cause })
  }).pipe(
    Effect.flatMap(Schema.decodeUnknownEffect(Schema.Array(schema))),
    Effect.mapError((cause) =>
      cause instanceof AirportDataError ? cause : new AirportDataError({ message: `Unexpected navdata shape: ${sql}`, cause })
    )
  )

const program = Effect.gen(function*() {
  const icao = (process.argv[2] ?? "KMSP").toUpperCase()
  const navdata = process.argv[3] ?? process.env.NAVDATA_PATH ?? `${homedir()}/Documents/SimToolkitPro/navdata.s3db`

  const db = yield* openReadonly(navdata)
  const [airport] = yield* query(db, AirportRow, "select * from tbl_airports where airport_identifier = ?", icao)
  if (airport === undefined) {
    return yield* new AirportDataError({ message: `${icao} is not in ${navdata}` })
  }
  const runways = yield* query(
    db,
    RunwayRow,
    "select * from tbl_runways where airport_identifier = ? order by runway_identifier",
    icao
  )
  const [header] = yield* query(db, HeaderRow, "select current_airac from tbl_header limit 1")

  const data: AirportData = {
    ident: airport.airport_identifier,
    name: airport.airport_name,
    latitude: airport.airport_ref_latitude,
    longitude: airport.airport_ref_longitude,
    elevationFt: airport.elevation,
    airac: header?.current_airac ?? "unknown",
    runways: runways.map((row) => ({
      ident: row.runway_identifier,
      latitude: row.runway_latitude,
      longitude: row.runway_longitude,
      trueBearing: row.runway_true_bearing,
      magneticBearing: row.runway_magnetic_bearing,
      lengthFt: row.runway_length,
      widthFt: row.runway_width,
      displacedThresholdFt: row.displaced_threshold_distance
    }))
  }

  const fs = yield* FileSystem.FileSystem
  const out = fileURLToPath(new URL(`../data/${icao}.json`, import.meta.url))
  yield* fs.writeFileString(out, JSON.stringify(data, null, 2) + "\n")
  const cpp = fileURLToPath(new URL("../../firmware/inkplate_atis/src/airport_data.cpp", import.meta.url))
  yield* fs.writeFileString(cpp, toCpp(data))
  yield* Console.log(`${icao}: ${data.runways.length} runway ends, AIRAC ${data.airac} -> ${cpp}`)
})

program.pipe(Effect.scoped, Effect.provide(BunServices.layer), BunRuntime.runMain)
